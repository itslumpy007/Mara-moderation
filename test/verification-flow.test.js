import test from 'node:test';
import assert from 'node:assert/strict';
import { rulesCard, rulesVersion } from '../src/verification.js';
import { defaultConfig, validateConfig } from '../src/config.js';
import { createStore } from '../src/store.js';
import { DatabaseSync } from 'node:sqlite';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
test('verification displays configured rules and acceptance is bound to their version',()=>{
 const card=rulesCard(defaultConfig);
 assert.equal(card.embeds[0].description,defaultConfig.verificationRules);
 assert.equal(card.components[0].components[0].custom_id,'verify-accept:'+rulesVersion(defaultConfig.verificationRules));
 assert.notEqual(rulesVersion('old rules'),rulesVersion('new rules'));
 assert.throws(()=>rulesCard({verificationRules:''}),/not configured/);
 assert.deepEqual(validateConfig({verificationRules:'Custom rules'}),{verificationRules:'Custom rules'});
 for(const verificationRules of ['', 'a'.repeat(1501), 12]) assert.throws(()=>validateConfig({verificationRules}));
});

test('new members receive Unverified and verification removes it, with cleanup retry',async t=>{
 const { createVerification }=await import('../src/verification.js');
 const { PermissionsBitField, PermissionFlagsBits:P }=await import('discord.js');
 const cache=new Map(),changes=[];
 const roles=Object.fromEntries(['verified','unverified'].map(id=>[id,{id,guild:{id:'g'},managed:false,editable:true,permissions:new PermissionsBitField()}]));
 let failRemoval=false;
 const member={id:'u',joinedTimestamp:100,user:{tag:'User',createdTimestamp:0,bot:false},guild:{id:'g',roles:{fetch:async id=>roles[id]},members:{fetch:async()=>member,fetchMe:async()=>({permissions:new PermissionsBitField(P.ManageRoles),roles:{highest:{comparePositionTo:()=>1}}})}},roles:{cache,add:async role=>{cache.set(role.id,role);changes.push('add:'+role.id);return member;},remove:async role=>{if(failRemoval)throw Error('remove failed');cache.delete(role.id);changes.push('remove:'+role.id);}}};
 const directory=mkdtempSync(join(tmpdir(),'mara-verification-'));
 const path=join(directory,'test.sqlite');
 let store=createStore(path);
 t.after(()=>{store.close();rmSync(directory,{recursive:true});});
 const env={VERIFIED_ROLE_ID:'verified',UNVERIFIED_ROLE_ID:'unverified'};
 const logs=[];
 const audit=async(_,message)=>logs.push(message);
 let verify=createVerification({store,env,audit});
 const acceptedVersion=rulesVersion(defaultConfig.verificationRules);
 store.recordJoin('g','u',100,true);
 store.set('verify-review:u',{status:'pending'});
 await verify.assignUnverified(member);await verify.assignUnverified(member);
 assert.deepEqual(changes,['add:unverified']);
 failRemoval=true;await assert.rejects(verify.grant(member,{acceptedVersion}),/remove failed/);
 assert.equal(cache.has('verified'),true);assert.equal(cache.has('unverified'),true);
 assert.equal(store.cases().length,0);
 assert.equal(store.get('verify-review:u').status,'pending');
 store.close();
 store=createStore(path);
 verify=createVerification({store,env,audit});
 store.set('config',{verificationRules:'Updated rules'});
 failRemoval=false;
 await verify.grant(member,{acceptedVersion:rulesVersion('Updated rules')});
 assert.equal(cache.has('unverified'),false);
 assert.equal(store.cases().length,1);
 assert.ok(store.onboarding('g','u').verified_at);
 assert.equal(store.onboarding('g','u').welcome_pending,1);
 assert.equal(store.get('verify-review:u'),null);
 const db=new DatabaseSync(path,{readOnly:true});
 const original=db.prepare('SELECT rules FROM rules_versions WHERE guild=? AND version=?').get('g',acceptedVersion);
 assert.equal(original.rules,defaultConfig.verificationRules);
 assert.ok(db.prepare('SELECT accepted_at FROM rules_acceptances WHERE guild=? AND member=? AND version=?')
   .get('g','u',acceptedVersion).accepted_at);
 db.close();
 await verify.grant(member,{acceptedVersion:rulesVersion('Updated rules')});
 assert.equal(store.latestRulesAcceptance('g','u').version,rulesVersion('Updated rules'));
 assert.equal(store.cases().length,1);
 assert.equal(logs.length,1);
 await verify.assignUnverified(member);assert.equal(cache.has('unverified'),false);
 cache.clear();member.user.bot=true;await verify.assignUnverified(member);assert.equal(cache.size,0);
 member.user.bot=false;
 await verify.grant(member,{staff:true,actor:'moderator'});
 assert.equal(store.latestRulesAcceptance('g','u').version,rulesVersion('Updated rules'));
 assert.equal(store.cases()[0].reason,'Staff approved verification');
 assert.match(logs.at(-1),/^Staff approved/);
 cache.clear();
 const invalid=createVerification({store,env:{VERIFIED_ROLE_ID:'verified',UNVERIFIED_ROLE_ID:'verified'},audit:async()=>{}});
 await assert.rejects(invalid.assignUnverified(member),/different roles/);
});
